/* =============================================================
   传承线索
   功法秘籍主要从这里与既有奇遇中引出。线索只是开头，
   真正拿到手还要过「寻迹 → 破禁 → 参悟」三关。
   ============================================================= */
function manualLeadOpts() {
  return [
    ['循着消息去探一探', '机', () => {
      const t = randomTech(Math.min(4, S.realm + 1));
      if (!t) { gainPct(0.08); return '你照着消息走了一趟，什么也没找着。这种事十有八九是空穴来风。'; }
      if (!startManualChain(t.id)) { gainPct(0.08); return '你走了几日，线索断在半路。'; }
      return '你顺着那些零碎的说法一路找去，竟真的摸到了《' + t.name + '》的一点影子。';
    }],
    ['花灵石买一份详图', '耗', () => {
      const cost = 10 + S.realm * 15;
      const t = randomTech(Math.min(4, S.realm + 1));
      if (!t) { gainPct(0.06); return '你买了图，按图找去，那地方早已被人搬空了。'; }
      addStones(-cost);
      startManualChain(t.id);
      return '你数出' + cost + '枚灵石推过去。他把图摊开，指给你看——图上标的，正是《' + t.name + '》的藏处。';
    }, () => S.stones >= 10 + S.realm * 15],
    ['多半是骗子，不理会', '稳', () => {
      gainPct(0.10); addMood(2);
      return '你听完就忘了。修仙界里最不缺的就是这种故事，也最不缺被故事骗死的人。';
    }],
  ];
}

